package io.github.dremo_drizzy.bustruth.api;

import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.Optional;

/**
 * Turns a managed host's {@code DATABASE_URL} into the three properties Spring wants.
 *
 * <p>Render — and Heroku, and most managed Postgres — hand you one variable:
 * {@code postgres://user:password@host:5432/database}. JDBC cannot use it. It needs
 * {@code jdbc:postgresql://host:5432/database} with the credentials supplied
 * separately, so something has to translate, and that something is here rather than in
 * a shell script nobody reads.
 *
 * <p>This exists because of a limitation worth knowing: a Render Blueprint can inject a
 * database's {@code connectionString}, {@code user}, {@code password} and
 * {@code database}, but <b>not its host or port</b>. The internal hostname is generated
 * when the database is created, so there is no way to write it into the Blueprint in
 * advance and no way to assemble a JDBC URL from the parts. Taking the whole connection
 * string and splitting it is the only route that keeps the credentials out of the
 * repository and out of anybody's hands.
 *
 * <h2>Why this does not use java.net.URI</h2>
 *
 * It did, and it was wrong in the one way that would only ever have been discovered in
 * production. <b>The password is generated by the host, not chosen</b>, and a password
 * containing {@code @}, {@code :} or {@code /} makes {@code URI.create} return no host
 * at all — so the translation silently produced nothing, the application fell back to
 * its localhost defaults, and the failure arrived as a connection refused that reads
 * like a firewall rule rather than a parsing bug.
 *
 * <p>So the authority is split by hand, on two rules that hold however strange the
 * password is: the credentials end at the <b>last</b> {@code @} (a host cannot contain
 * one), and the username ends at the <b>first</b> {@code :} (a username cannot contain
 * one). Percent-encoding is then decoded, because the driver is handed the password as
 * a property rather than inside a URL and needs it literal.
 *
 * <p>Local development is unaffected: without {@code DATABASE_URL} nothing here fires,
 * and {@code application.yml}'s {@code POSTGRES_HOST}/{@code POSTGRES_PORT} defaults
 * still point at the compose database on 55432.
 */
public final class DatabaseUrl {

    private static final String[] SCHEMES = {"postgres://", "postgresql://"};

    private DatabaseUrl() {
    }

    /**
     * Translates {@code DATABASE_URL} into system properties, if it is set.
     *
     * <p>Called before the Spring context starts, so the properties are in place by the
     * time the datasource is built. Set as system properties rather than injected by an
     * environment post-processor: one line in {@code main} that anybody can follow beats
     * a registration file whose silent absence would look like a connection failure.
     *
     * <p>Anything already set explicitly wins, so a deployment can always override this
     * by providing {@code spring.datasource.url} itself.
     */
    public static void applyIfPresent(String databaseUrl) {
        Translation translation = translate(databaseUrl).orElse(null);
        if (translation == null) {
            return;
        }
        setIfAbsent("spring.datasource.url", translation.jdbcUrl());
        setIfAbsent("spring.datasource.username", translation.username());
        setIfAbsent("spring.datasource.password", translation.password());
    }

    /**
     * Parses a {@code postgres://} or {@code postgresql://} URL.
     *
     * @return empty when there is nothing usable to translate, so that a missing or
     *         malformed variable leaves local configuration alone rather than
     *         half-applying
     */
    public static Optional<Translation> translate(String databaseUrl) {
        if (databaseUrl == null || databaseUrl.isBlank()) {
            return Optional.empty();
        }
        String rest = afterScheme(databaseUrl.trim());
        if (rest == null) {
            return Optional.empty();
        }

        // Credentials end at the LAST @: a hostname cannot contain one, a generated
        // password can.
        String credentials = "";
        int lastAt = rest.lastIndexOf('@');
        if (lastAt >= 0) {
            credentials = rest.substring(0, lastAt);
            rest = rest.substring(lastAt + 1);
        }

        // Then the host and port end at the first / or ?, whichever comes first.
        String hostPort = rest;
        String pathAndQuery = "";
        int pathStart = indexOfFirst(rest, '/', '?');
        if (pathStart >= 0) {
            hostPort = rest.substring(0, pathStart);
            pathAndQuery = rest.substring(pathStart);
        }
        if (hostPort.isEmpty()) {
            return Optional.empty();
        }

        String host = hostPort;
        int port = 5432;
        int colon = hostPort.lastIndexOf(':');
        if (colon >= 0) {
            host = hostPort.substring(0, colon);
            try {
                // Managed hosts often omit the port and mean 5432. The local compose
                // database is on 55432 and is reached through POSTGRES_PORT instead.
                port = Integer.parseInt(hostPort.substring(colon + 1));
            } catch (NumberFormatException notAPort) {
                return Optional.empty();
            }
        }
        if (host.isEmpty()) {
            return Optional.empty();
        }

        // The query string is carried across verbatim: managed Postgres commonly
        // appends ?sslmode=require, and dropping it turns a working URL into a refused
        // connection that looks like a network problem.
        String database = pathAndQuery;
        String query = "";
        int queryStart = pathAndQuery.indexOf('?');
        if (queryStart >= 0) {
            database = pathAndQuery.substring(0, queryStart);
            query = pathAndQuery.substring(queryStart);
        }
        database = database.replaceFirst("^/", "");

        // The username ends at the FIRST colon; everything after it is the password,
        // colons and slashes and all.
        String username = credentials;
        String password = "";
        int split = credentials.indexOf(':');
        if (split >= 0) {
            username = credentials.substring(0, split);
            password = credentials.substring(split + 1);
        }

        return Optional.of(new Translation(
                "jdbc:postgresql://" + host + ":" + port + "/" + database + query,
                decode(username),
                decode(password)));
    }

    private static String afterScheme(String url) {
        for (String scheme : SCHEMES) {
            if (url.regionMatches(true, 0, scheme, 0, scheme.length())) {
                return url.substring(scheme.length());
            }
        }
        return null;
    }

    private static int indexOfFirst(String value, char a, char b) {
        int first = value.indexOf(a);
        int second = value.indexOf(b);
        if (first < 0) {
            return second;
        }
        if (second < 0) {
            return first;
        }
        return Math.min(first, second);
    }

    /**
     * Decodes percent-escapes, and nothing else.
     *
     * <p>Not {@code URLDecoder}: that also turns {@code +} into a space, which is
     * correct for form encoding and wrong for a password — a generated password
     * containing a plus would authenticate with a space in its place and fail as a bad
     * credential. Bytes are gathered and decoded as UTF-8 at the end so that a
     * multi-byte character written as two escapes survives. A stray {@code %} that is
     * not followed by two hex digits is left alone, because a raw password is likelier
     * than a malformed escape.
     */
    private static String decode(String value) {
        if (value.indexOf('%') < 0) {
            return value;
        }
        ByteArrayOutputStream bytes = new ByteArrayOutputStream(value.length());
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            if (c == '%' && i + 2 < value.length()
                    && isHex(value.charAt(i + 1)) && isHex(value.charAt(i + 2))) {
                bytes.write(Integer.parseInt(value.substring(i + 1, i + 3), 16));
                i += 2;
            } else {
                bytes.writeBytes(String.valueOf(c).getBytes(StandardCharsets.UTF_8));
            }
        }
        return bytes.toString(StandardCharsets.UTF_8);
    }

    private static boolean isHex(char c) {
        return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F');
    }

    private static void setIfAbsent(String key, String value) {
        if (System.getProperty(key) == null && !value.isEmpty()) {
            System.setProperty(key, value);
        }
    }

    /** The three values Spring needs, with the password kept out of {@code toString}. */
    public record Translation(String jdbcUrl, String username, String password) {
        @Override
        public String toString() {
            return "Translation[jdbcUrl=%s, username=%s, password=***]"
                    .formatted(jdbcUrl, username);
        }
    }
}
